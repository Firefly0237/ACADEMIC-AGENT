export function taskFailureText(code: string): string {
  if (/unknown|unresolved_attempt|attempt_unresolved/.test(code)) return "调用结果尚未确定，已停止继续派发。原调用和费用预留保留，需先核对。";
  if (/deadline|timeout/.test(code)) return "本次执行达到允许时限，已停止。未通过的记录保留，可查看最后完成的步骤。";
  if (/budget|capacity|quota/.test(code)) return "剩余资源不足以完成下一步，已停止派发。已用资源与当前缺口保留。";
  if (/evidence|source|access|permission|rights/.test(code)) return "来源、引用或访问范围未通过核验，已停止；未核准内容不会作为完整答案发布。";
  if (/review|schema|typed|validation|content|format/.test(code)) return "候选回答未通过结构或内容核验，当前未发布。可查看执行过程和具体错误标识。";
  if (/runtime|version|catalog.*policy/.test(code)) return "该任务需要匹配的执行服务，当前版本未继续接管。历史结果和原费用记录保留。";
  return "本轮任务未完成，失败记录已保留。请查看执行过程了解停止位置。";
}
export function progressText(event: Record<string, any>): string {
  const type = event.event_type || event.type || event.kind || "";
  if (type === "workflow_progress") {
    const phase = event.payload?.phase || "";
    const state =
      (
        {
          started: "进行中",
          completed: "完成",
          waiting: "等待补充",
          failed: "未通过",
        } as Record<string, string>
      )[event.payload?.state] || "状态更新";
    return `${phases[phase] || "研究步骤"} · ${state}`;
  }
  return types[type] || "任务状态更新";
}
