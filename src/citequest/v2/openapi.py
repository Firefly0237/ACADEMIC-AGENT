"""Official FastAPI OpenAPI generation with the accepted response JSON Schemas."""

from __future__ import annotations

from typing import Any

from fastapi import FastAPI
from fastapi.openapi.utils import get_openapi


def response_contracts(app: FastAPI, schema: dict[str, Any]) -> None:
    def refs(value: Any) -> Any:
        if isinstance(value, dict):
            return {key: refs(item) for key, item in value.items()}
        if isinstance(value, list):
            return [refs(item) for item in value]
        if isinstance(value, str) and value.startswith("#/$defs/"):
            return value.replace("#/$defs/", "#/components/schemas/", 1)
        return value

    def generated() -> dict[str, Any]:
        if app.openapi_schema:
            return app.openapi_schema
        value = get_openapi(title=app.title, version=app.version, routes=app.routes)
        components = value.setdefault("components", {})
        components.setdefault("schemas", {}).update(refs(schema["$defs"]))
        components["securitySchemes"] = {
            "localSession": {"type": "apiKey", "in": "cookie", "name": "citequest_session"}
        }
        scalar = {
            "works": "Work",
            "items": "LibraryItem",
            "collections": "Collection",
            "notes": "Note",
            "files": "File",
            "history": "History",
            "capabilities": "CapabilityManifest",
        }
        for path, methods in value["paths"].items():
            if not path.startswith("/api/v2/"):
                continue
            parts = path.split("/")[3:]
            for method, operation in methods.items():
                if method not in {"get", "post", "put", "patch", "delete"}:
                    continue
                kind = "LibraryItem" if "library" in parts else scalar[parts[0]]
                is_page = method == "get" and path.endswith(("/items", "/collections", "/notes", "/history"))
                output = {"$ref": "#/components/schemas/" + kind}
                if is_page:
                    output = {
                        "allOf": [{"$ref": "#/components/schemas/Page"}, {"properties": {"items": {"items": output}}}],
                    }
                status = "201" if method == "post" and not path.endswith("/restore") else "200"
                operation["responses"] = {
                    status: {
                        "description": "Validated domain response",
                        "content": {"application/json": {"schema": output}},
                    }
                }
                for code in (400, 401, 403, 404, 409, 415, 422, 500, 503):
                    operation["responses"][str(code)] = {
                        "description": "Structured domain error",
                        "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}}},
                    }
                if parts != ["capabilities"]:
                    operation["security"] = [{"localSession": []}]
                if method != "get":
                    operation.setdefault("parameters", []).extend(
                        [
                            {"name": "Origin", "in": "header", "required": True, "schema": {"type": "string"}},
                            {"name": "X-CSRF-Token", "in": "header", "required": True, "schema": {"type": "string"}},
                        ]
                    )
                operation["x-implementation-state"] = "implemented"
        value["info"]["description"] = (
            "S03 implemented loopback domain subset. Canonical response schemas copied from the frozen S02 contract; "
            "request schemas generated by Pydantic. No parser, search, generation or public login endpoint is claimed."
        )
        app.openapi_schema = value
        return value

    app.openapi = generated
